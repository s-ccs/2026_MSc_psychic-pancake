# ╔═╡ 3b9c1128-42ff-4421-8457-45c9bbbebf5c
function test_run(;
		n_subjects = 200,
		n_items = 200,
		ratio_subject_intercept,
		ratio_subject_slope,
		ratio_item_intercept = 0.5,
		ratio_item_slope = ratio_item_slope_B, # Design B only
		sd_residual,
		seeds = Dict("A" => (1, 2), "B" => (3, 4)),
		)
	rows = NamedTuple[]
	for design in ["A", "B"]
		# make the design
		d = make_design(design; n_subjects, n_items)
		# make the components
		item_slope = design == "B" ? ratio_item_slope : nothing # no item slope in Design A
		component = make_component(design; ratio_subject_intercept, ratio_subject_slope, ratio_item_intercept, ratio_item_slope = item_slope, sd_residual)
		# simulate the dataset
		seed_effects, seed_noise = seeds[design]
		data = simulate_dataset(seed_effects, seed_noise, d, component; sd_residual)
		# making sure that only M4 and M5 are used
		model_name = Dict("A" => "M4", "B" => "M5")[design]
		model = only(m for m in models if m.name == model_name)
		# fit the model
		fitted = fit_quietly(model.full, data, design2contrasts[design])

		# append to rows list
		push!(rows, (; Model = model.name, design = design, measure = "effect", set = 0.0, estimate = coef(fitted)[2])) # coef():[<Intercept>, <condition effect>]
		push!(rows, (; Model = model.name, design = design, measure = "subject intercept SD", set = ratio_subject_intercept * sd_residual, estimate = estimated_sd(fitted, :subject, 1))) # SD at idx_1=intercept for group subjects
		push!(rows, (; Model = model.name, design = design, measure = "subject slope SD", set = ratio_subject_slope * sd_residual, estimate = estimated_sd(fitted, :subject, 2))) # SD at idx_2=slope for group subjects
		push!(rows, (; Model = model.name, design = design, measure = "item intercept SD", set = ratio_item_intercept * sd_residual, estimate = estimated_sd(fitted, :item, 1))) # SD at idx_1=intercept for group items
		if design == "B"
			push!(rows, (; Model = model.name, design = design, measure = "item slope SD", set = ratio_item_slope * sd_residual, estimate = estimated_sd(fitted, :item, 2))) # SD at idx_2=slope for group items
		end
		push!(rows, (; Model = model.name, design = design, measure = "residual SD", set = sd_residual, estimate = fitted.sigma)) # residual SD (trial-level noise)
	end
	table = DataFrame(rows)
	table.estimate = round.(table.estimate; digits = 3)
	return table
end

