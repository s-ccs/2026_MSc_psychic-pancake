function run_condition(condition, n_rep)
	# make the design (wie oben)
	d = make_design(condition.design; n_subjects, n_items)
	# make the components
	component = make_component(condition.design;
		ratio_subject_intercept = condition.ratio_subject_intercept,
		ratio_subject_slope = condition.ratio_subject_slope,
		ratio_item_intercept = condition.ratio_item_intercept,
		ratio_item_slope = condition.ratio_item_slope,
		sd_residual)

	rows = NamedTuple[]
	for rep in 1:n_rep
		# simulate a new dataset
		data = simulate_dataset(master_seed+2*rep, master_seed+2*rep+1, d, component; sd_residual)
		# analyse the dataset with all models M1-4(+5) and T-Test and add it to a BIIG dataframe
		for row in analyse_dataset(data, condition.design)
			push!(rows, (; condition_id = condition.condition_id, 
				design = condition.design, # "A" or "B"
				varied = condition.varied, # "item intercept" or "item slope"
				ratio = condition.x, # value of the varied parameter
				rep, row...)) # `row...` adds the whole result from analyse_dataset
		end
	end
	return DataFrame(rows)
end

