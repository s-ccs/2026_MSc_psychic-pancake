# go through every condition in your conditions table and run_condition for each
function run_simulation(conditions, n_rep)
	df = DataFrame[]
	@progress for condition in eachrow(conditions)
		# add the analyses returned by run_condition to even BIIGGEERR Dataframe
		push!(df, run_condition(condition, n_rep))
	end
	# stack the per-condition tables on top of each other into one results table
	return reduce(vcat, df)
end

