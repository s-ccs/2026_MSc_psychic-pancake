# ╔═╡ a007ac8b-ada5-4042-bf0f-e4116f1639b4
# Fit without any warnings/ progress bar; why? to avoid too much output/ slowing down the code
function fit_quietly(
	formula, 
	data, 
	contrasts; 
	REML = false # Restricted Maximum Likelihood depends on the fixed affects, but Full and Null differ in fixed effects, so their REML likelihoods are not comparable -> ML = true
	)
	
	with_logger(NullLogger()) do
		fit(MixedModel, formula, data; contrasts = contrasts, REML = REML, progress = false)
	end
end

# ╔═╡ 3e79923c-5e86-4455-9eba-c5d6f13a1fea
# Provide the estimated SD of a model for different groups.
function estimated_sd(fitted_model, group, index)
	if haskey(fitted_model.σs, group) # check for random effect for this group
		sds = values(fitted_model.σs[group]) # format: (intercept, slope)
		if index <= length(sds) 
			return sds[index] # the SD at either idx_1=intercept or idx_2=slope
		else
			return NaN
		end
	else 
		return NaN
	end
end

# ╔═╡ 1a086fa9-f4d6-4243-96e8-61471974a045
function analyse_lmm(model, data, contrasts)
	fit_full = fit_quietly(model.full, data, contrasts) # with condition
	fit_null = fit_quietly(model.null, data, contrasts) # without condition
	estimate = coef(fit_full)[2] # estimated effect (full ofc)
	se = stderror(fit_full)[2]
	# Likelihood-Ratio-Test: how much better does a model with condition fit
	likelihood_ratio = max(2 * (loglikelihood(fit_full) - loglikelihood(fit_null)), 0.0)
	# Compute the Likelihood Ratio Test p-value using a Chi-square distribution with 1 degree of freedom
	p_lrt = ccdf(Chisq(1), likelihood_ratio)
	#TBD: Bene meinte ich soll vlt auch einfach t-test nehmen?
	return (; model = model.name, estimate, se, p_lrt, p_t = NaN,
		singular = issingular(fit_full), # how often variance estimate = 0 
		sd_item_intercept_pred = estimated_sd(fit_full, :item, 1),
		sd_item_slope_pred = estimated_sd(fit_full, :item, 2),
		sd_residual_pred = fit_full.sigma) # ';' makes it a faster NamedTuple
end

# ╔═╡ 07050fec-84fc-4142-a50a-9fd7a0ab17a1
function t_test(data, levels)
	# mean over subjects and condition
	grouped = groupby(data, [:subject, :condition])
	means = combine(grouped, :amplitude => mean => :amplitude)
	# format for t-test
	pivot = unstack(means, :subject, :condition, :amplitude)
	disallowmissing!(pivot) # all subjects have both conditions → plain Float64 columns
	# paired t-test over subjects; paired because within subject design
	test = OneSampleTTest(pivot[!, levels[2]], pivot[!, levels[1]]) # ! = all rows
	
	return (; model = "F1", estimate = test.xbar, se = test.stderr, p_lrt = NaN, p_t = pvalue(test),
		singular = false, sd_item_intercept_pred = NaN, sd_item_slope_pred = NaN, sd_residual_pred = NaN)
end

# ╔═╡ 866e4d60-4484-4218-8ae9-9896f545b10b
# collects all analyses
function analyse_dataset(data, design)
	rows = NamedTuple[]
	for model in models
		if design in model.designs
			push!(rows, analyse_lmm(model, data, design2contrasts[design])) # rows.append() in python
		else
			continue
		end
	end
	push!(rows, t_test(data, design2levels[design]))
	return rows
end

