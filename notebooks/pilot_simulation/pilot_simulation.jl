# ╔═╡ a96e2558-ddaa-48c7-a07c-8c058ab9358f
md"""
## 2. Create the Data

``\text{amplitude} = \underbrace{\beta_0 + \beta_1 x}_{\text{fixed effects}} + \underbrace{S_0 + S_1 x}_{\text{subject}} + \underbrace{I_0 + I_1 x}_{\text{item}} + \underbrace{\varepsilon}_{\text{noise}}``

Where:
- ``x`` = encoded condition (−0.5 oder +0.5).
- ``\beta_1 = 0`` is the effect caused by the condition, which is 0 here
- ``S_0`` und ``I_0`` are the intercepts for _S_ubject and _I_tem
- ``S_1`` und ``I_1`` are the slopes for _S_ubject and _I_tem
- For Design A (nested items) we don't have any item-slope
- Design B (crossed items) always has a random item intercept **and** a random item slope; M5 is the matching model


`make_component` describes the fixed and random effects. 

Note for later: `basis = [1.0]` means one value per trial.
"""

# ╔═╡ 903a1fde-3ee6-4408-aa6c-53a2f827b51c
function make_component(
		design; # positional args until ";"
		ratio_subject_intercept, 
		ratio_subject_slope, 
		ratio_item_intercept,
		ratio_item_slope = nothing, # Design A: leave out (no item slope); Design B: required
		sd_residual, 
		effect = 0.0
		)
	# Design A has no item slope; Design B always has item intercept AND item slope
	if design == "A"
		if !(isnothing(ratio_item_slope) || ratio_item_slope == 0)
			error("Design A has no item slope (items are between conditions)")
		end
		ratio_item_slope = 0.0
	else
		if isnothing(ratio_item_slope)
			error("Design B needs ratio_item_slope (random item intercept and slope)")
		end
	end
	# absolute SDs = ratios * residual-SD
	sd_subject = [ratio_subject_intercept, ratio_subject_slope] .* sd_residual
	sd_item = [ratio_item_intercept, ratio_item_slope] .* sd_residual
	if design == "A"
		return MixedModelComponent(;
			basis = [1.0], # one value per trial
			formula = @formula(0 ~ 1 + condition + (1 + condition | subject) + (1 | item)), # random subject intercept & slope, random item intercept
			β = [0.0, effect], # [fixed intercept, fixed slope]
			σs = Dict(:subject => sd_subject, :item => sd_item[1:1]), # SDs for subjects and items
			contrasts = contrasts_A, # contrast coding +/- 0.5
		)
	else
		return MixedModelComponent(;
			basis = [1.0],
			formula = @formula(0 ~ 1 + condition + (1 + condition | subject) + (1 + condition | item)), # random subject intercept & slope, random item intercept & slope
			β = [0.0, effect],
			σs = Dict(:subject => sd_subject, :item => sd_item),
			contrasts = contrasts_B,
		)
	end
end

