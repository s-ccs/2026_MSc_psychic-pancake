# ╔═╡ cb61cbba-2fd5-49e4-b179-f36878bbaa26
function simulate_dataset(
	seed_effects, 
	seed_noise, 
	design_object, 
	component; 
	sd_residual)
	
	rng_effects = StableRNG(seed_effects)
	rng_noise = StableRNG(seed_noise)
	# trial table: regenerate on every call such that it can be mutated below 
	data = UnfoldSim.generate_events(rng_effects, design_object)
	# signal from fixed and random effects
	signal = vec(UnfoldSim.simulate_component(rng_effects, component, design_object))
	# noise & make amplitude column 
	data.amplitude = signal .+ sd_residual .* randn(rng_noise, length(signal))
	return data
end

