# Build the table of simulation conditions
# Design A: vary item intercept
# Design B: vary item slope, item intercept stays constant
function build_conditions(;
		ratio_grid,
		ratio_subject_intercept,
		ratio_subject_slope,
		ratio_item_intercept_B,
		)
	rows = NamedTuple[]

	# Design A: vary item intercept, no item slope
	for ratio in ratio_grid
		push!(rows, (; design = "A", varied = "item intercept", x = ratio,
			ratio_subject_intercept = ratio_subject_intercept,
			ratio_subject_slope = ratio_subject_slope,
			ratio_item_intercept = ratio,
			ratio_item_slope = 0.0))
	end

	# Design B: vary item slope, item intercept fixed
	for ratio in ratio_grid
		push!(rows, (; design = "B", varied = "item slope", x = ratio,
			ratio_subject_intercept = ratio_subject_intercept,
			ratio_subject_slope = ratio_subject_slope,
			ratio_item_intercept = ratio_item_intercept_B,
			ratio_item_slope = ratio))
	end

	table = DataFrame(rows)
	insertcols!(table, 1, :condition_id => 1:nrow(table))
	return table
end

